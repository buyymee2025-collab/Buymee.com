import assert from 'node:assert/strict'
import fs from 'node:fs'

const data = fs.readFileSync(new URL('../src/data/refreshedCatalog.js', import.meta.url), 'utf8')
const source = fs.readFileSync(new URL('../src/data/products.js', import.meta.url), 'utf8')
  .replaceAll("'./refreshedCatalog'", JSON.stringify('data:text/javascript,' + encodeURIComponent(data)))
const { default: products } = await import('data:text/javascript,' + encodeURIComponent(source))
const audit = JSON.parse(fs.readFileSync(new URL('../catalog-audit/cloudinary-first-755.json', import.meta.url)))

assert.equal(audit.images.length, 755)
assert.deepEqual(audit.images.map(image => image.number), Array.from({ length: 755 }, (_, i) => i + 1))
assert.equal(new Set(products.map(product => product.id)).size, products.length)
assert.equal(new Set(products.map(product => product.slug)).size, products.length)
for (const image of audit.images) {
  const product = products.find(product => product.id === image.productId)
  assert.ok(product, `Image ${image.number} has a product or documented replacement`)
  if (image.status === 'included') assert.ok(product.gallery.includes(image.url))
  if (image.status === 'black-mannequin-replaced') assert.ok(!product.gallery.includes(image.url))
}
for (const product of products) {
  assert.ok(product.gallery.includes(product.image), product.name)
  assert.ok(product.variants.every(variant => variant.media.length > 0), product.name)
}
const watches = products.filter(product => product.category === 'Watches')
assert.equal(watches.reduce((count, product) => count + product.variants.length, 0), 50)
assert.equal(new Set(watches.map(product => `${product.parentProductId}:${product.familyName}`)).size, watches.length)
assert.ok(watches.every(product => product.media.every(item => !item.src.includes('1006_4'))))
assert.equal(products.filter(product => product.category === 'Sneakers').length, 81)
console.log('Catalog checks passed: 755 images accounted for, unique listings, 50 watch colors retained, 81 footwear listings preserved.')

// Regressions from the manual frame/hinge/temple review.
const eyewear = products.filter(product => product.category === 'Eye Wears')
const eyewearRecords = audit.products.filter(product => product.category === 'Eye Wears')
const eyewearSources = eyewearRecords.flatMap(product => product.sourceImageNumbers)
assert.equal(eyewearSources.length, 475)
assert.equal(new Set(eyewearSources).size, 475)
const recordFor = number => eyewearRecords.find(product => product.sourceImageNumbers.includes(number))
const sameModel = (...numbers) => assert.equal(new Set(numbers.map(number => recordFor(number).id)).size, 1, `Same frame: ${numbers}`)
const differentModels = (left, right) => assert.notEqual(recordFor(left).id, recordFor(right).id, `Different frames: ${left}, ${right}`)
sameModel(244, 246, 264)
sameModel(292, 311)
sameModel(369, 373, 378, 376, 379, 531)
sameModel(380, 368)
sameModel(374, 372)
sameModel(485, 621, 604, 605)
sameModel(528, 585, 541, 595)
sameModel(646, 645, 610, 644)
sameModel(507, 525, 653)
sameModel(459, 489, 649)
sameModel(452, 482)
sameModel(616, 561, 473)
sameModel(548, 671)
differentModels(434, 530)
differentModels(566, 481)
differentModels(477, 616)
differentModels(631, 616)
sameModel(534, 600)
sameModel(584, 641)
sameModel(635, 526)
for (const number of [241, 460, 489]) assert.equal(audit.images[number - 1].status, 'included')
for (const number of [621, 605, 585, 595, 645, 644, 373, 378]) assert.equal(audit.images[number - 1].status, 'duplicate-upload')
const allEyewearUrls = eyewear.flatMap(product => product.gallery)
assert.equal(new Set(allEyewearUrls).size, allEyewearUrls.length, 'No photograph appears in multiple listings')
for (const product of eyewear) {
  assert.ok(product.variants.every(variant => variant.media.every(media => product.gallery.includes(media.src))))
  assert.deepEqual(new Set(product.variants.flatMap(variant => variant.media.map(media => media.src))), new Set(product.gallery))
}
console.log(`Eyewear checks passed: ${eyewear.length} listings, all 475 source images accounted for, matching views and colour variants grouped.`)
